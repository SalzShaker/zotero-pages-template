// Fetches a Zotero library through the Zotero Web API (v3) and renders it.
// You normally only edit config.js.
const API = "https://api.zotero.org";
const base = `${API}/${CONFIG.libraryType}/${CONFIG.libraryId}`;
const scope = CONFIG.collectionKey ? `${base}/collections/${CONFIG.collectionKey}` : base;
const $ = id => document.getElementById(id);

// One page of results; the API sends at most 100 per request
async function getPage(url) {
  const r = await fetch(url, { headers: { "Zotero-API-Version": "3" } });
  if (!r.ok) throw new Error(`${r.status} ${r.statusText} – ${url}`);
  return { items: await r.json(), total: Number(r.headers.get("Total-Results")) };
}

// Pagination: ask for start=0, 100, 200 … until everything is there
async function getAll(path, params, max = CONFIG.maxItems) {
  let all = [], start = 0, total = Infinity;
  while (start < total && start < max) {
    const q = new URLSearchParams({ ...params, limit: 100, start });
    const page = await getPage(`${path}?${q}`);
    total = page.total; all = all.concat(page.items); start += 100;
    $("status").textContent = `Loading … ${all.length} of ${total}`;
  }
  return all;
}

// Data written by the GitHub Action (source: "file")
async function getFile(path) {
  const r = await fetch(path, { cache: "no-cache" });
  if (!r.ok) throw new Error(`${r.status} – ${path} not found. Has the GitHub Action «Update Zotero data» run?`);
  return r.json();
}

// Zotero notes are HTML: keep the text only (safer than inserting foreign HTML)
function noteText(html) {
  const doc = new DOMParser().parseFromString(html, "text/html");
  doc.querySelectorAll("p, br, li, h1, h2, h3").forEach(el => el.append("\n"));
  return doc.body.textContent.trim();
}

function groupKey(item) {
  const d = item.data;
  if (CONFIG.groupBy === "year") return (item.meta.parsedDate || "").slice(0, 4) || "No date";
  if (CONFIG.groupBy === "type") return d.itemType;
  if (CONFIG.groupBy === "tag") return d.tags.length ? d.tags[0].tag : "Untagged";
  return "";
}

function render(items, notes) {
  const out = $("bibliography");
  out.innerHTML = "";
  const groups = new Map();
  for (const it of items) {
    const k = groupKey(it);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(it);
  }
  const last = ["No date", "Untagged"];
  const keys = [...groups.keys()].sort((a, b) =>
    (last.includes(a) - last.includes(b)) || (CONFIG.groupBy === "year" ? b.localeCompare(a) : a.localeCompare(b)));
  for (const k of keys) {
    if (k) { const h = document.createElement("h2"); h.textContent = k; out.append(h); }
    for (const it of groups.get(k)) {
      const div = document.createElement("div");
      div.className = "entry";
      div.innerHTML = it.bib;                 // formatted citation, generated by Zotero (CSL)
      const tags = it.data.tags.map(t => t.tag);
      if (tags.length) {
        const t = document.createElement("div"); t.className = "tags";
        tags.forEach(tag => { const s = document.createElement("span"); s.className = "tag"; s.textContent = tag; t.append(s); });
        div.append(t);
      }
      for (const n of notes.get(it.key) || []) {
        const p = document.createElement("div"); p.className = "note"; p.textContent = n; div.append(p);
      }
      div.dataset.search = (div.textContent + " " + it.data.date).toLowerCase();
      out.append(div);
    }
  }
}

function filter() {
  const q = $("filter").value.toLowerCase().trim();
  let shown = 0;
  document.querySelectorAll(".entry").forEach(e => {
    const hit = !q || e.dataset.search.includes(q);
    e.hidden = !hit; if (hit) shown++;
  });
  document.querySelectorAll("#bibliography h2").forEach(h => {
    let n = h.nextElementSibling, any = false;
    while (n && n.tagName !== "H2") { if (!n.hidden) any = true; n = n.nextElementSibling; }
    h.hidden = !any;
  });
  $("status").textContent = `${shown} entries`;
}

async function main() {
  document.title = CONFIG.title;
  $("title").textContent = CONFIG.title;
  $("intro").textContent = CONFIG.intro;
  $("source").href = `https://www.zotero.org/${CONFIG.libraryType}/${CONFIG.libraryId}` +
                     (CONFIG.collectionKey ? `/collections/${CONFIG.collectionKey}` : "");
  const fromFile = CONFIG.source === "file";
  if (fromFile) {
    // private library: the data comes from the GitHub Action, the API link would not work for visitors
    $("source").removeAttribute("href");
    $("dl-bibtex").textContent = "JSON"; $("dl-bibtex").href = "data/items.json";
    $("dl-csljson").parentNode.removeChild($("dl-csljson").previousSibling);
    $("dl-csljson").remove();
  } else {
    $("dl-bibtex").href = `${scope}/items/top?format=bibtex&limit=100`;
    $("dl-csljson").href = `${scope}/items/top?format=csljson&limit=100`;
  }
  try {
    const items = fromFile ? await getFile("data/items.json")
      : await getAll(`${scope}/items/top`, { include: "bib,data", style: CONFIG.style, sort: "creator" });
    const notes = new Map();
    if (CONFIG.showNotes) {
      // child notes of the whole library (collections do not list child notes)
      const all = fromFile ? await getFile("data/notes.json") : await getAll(`${base}/items`, { itemType: "note" }, 1000);
      for (const n of all) {
        const p = n.data.parentItem; if (!p) continue;
        if (!notes.has(p)) notes.set(p, []);
        notes.get(p).push(noteText(n.data.note));
      }
    }
    render(items, notes);
    filter();
  } catch (err) {
    $("status").className = "error";
    $("status").textContent = `Could not load the library (${err.message}). ` +
      (fromFile ? "Check the Actions tab: did «Update Zotero data» run successfully?"
               : "Check libraryType, libraryId and collectionKey in config.js – and that the library is public.");
  }
}

$("filter").addEventListener("input", filter);
main();
